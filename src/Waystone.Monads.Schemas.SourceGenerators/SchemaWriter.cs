namespace Waystone.Monads.Schemas.SourceGenerators;

using System.Text;

internal static class SchemaWriter
{
    public const string InstanceMember = "Instance";

    public const string FieldsMember = "Fields";

    public const string EntryPointType = "Schema";

    public const string LadderType = "FieldSet";

    private const string Root = "global::Waystone.Monads.Schemas.";

    private const string Field = Root + "Field";

    private const string Accumulator = Root + "FieldAccumulator";

    private const string Violation = Root + "SchemaViolation";

    private const string CheckedValue = Root + "Checked";

    private const string Result = "global::Waystone.Monads.Results.Result";

    private const string AutoGeneratedHeader = "// <auto-generated/>";

    /// <summary>
    /// Emits the reopened declaration of one schema.
    /// </summary>
    /// <param name="model">What the transform learned about the schema.</param>
    /// <param name="constrained">
    /// Whether the consumer's language version can spell <c>notnull</c>. It cannot
    /// before C# 8, where the word parses as a missing type rather than as a
    /// constraint, and the constraint is unnecessary there anyway because nothing
    /// checks nullability.
    /// </param>
    /// <returns>The complete text of the generated file.</returns>
    public static string Emit(SchemaModel model, bool constrained)
    {
        var writer = new Writer();

        writer.Line(0, AutoGeneratedHeader);
        writer.Blank();

        var depth = 0;

        if (model.Namespace.Length > 0)
        {
            writer.Line(0, "namespace " + model.Namespace);
            writer.Line(0, "{");
            depth = 1;
        }

        foreach (string container in model.Containers.Values)
        {
            writer.Line(depth, container);
            writer.Line(depth, "{");
            depth++;
        }

        writer.Line(depth, model.Declaration);
        writer.Line(depth, "{");

        WriteInstance(writer, depth + 1, model);

        if (model.Arities.Length > 0)
        {
            writer.Blank();
            WriteEntryPoint(writer, depth + 1, model, constrained);

            foreach (int arity in model.Arities.Values)
            {
                writer.Blank();
                WriteFieldSet(writer, depth + 1, arity, constrained);
            }
        }

        writer.Line(depth, "}");

        while (depth > 0)
        {
            depth--;
            writer.Line(depth, "}");
        }

        return writer.ToString();
    }

    private static void WriteInstance(Writer writer, int depth, SchemaModel model)
    {
        writer.Line(
            depth,
            "/// <summary>The shared <c>" + model.Name + "</c>.</summary>");

        writer.Line(
            depth,
            "/// <remarks>A schema holds nothing that belongs to one parse, so a single instance serves every call. Reach for this rather than constructing another, including where a schema is the item of a list or a field of an enclosing schema.</remarks>");

        writer.Line(
            depth,
            model.Accessibility
          + " static "
          + model.QualifiedName
          + " "
          + InstanceMember
          + " { get; } = new "
          + model.QualifiedName
          + "();");
    }

    /// <summary>
    /// The nested <c>Schema</c> class, which is how an uncapped <c>Fields</c> ladder
    /// is reached at all. A generator cannot add an overload to a type in another
    /// assembly, so it derives a class from that type here and adds the overload to
    /// the derived one. Static members are inherited in C#, so every other
    /// <c>Schema</c> member still resolves through it unchanged.
    /// </summary>
    private static void WriteEntryPoint(
        Writer writer,
        int depth,
        SchemaModel model,
        bool constrained)
    {
        writer.Line(
            depth,
            "/// <summary>The schema entry point, widened for <c>" + model.Name + "</c>.</summary>");

        writer.Line(
            depth,
            "/// <remarks>Adds the <c>Fields</c> overloads this schema uses and inherits every other member of the schema entry point unchanged.</remarks>");

        writer.Line(
            depth,
            "private sealed class " + EntryPointType + " : " + Root + "Schema");
        writer.Line(depth, "{");

        WriteCombine(writer, depth + 1);

        foreach (int arity in model.Arities.Values)
        {
            writer.Blank();
            WriteFieldsOverload(writer, depth + 1, arity, constrained);
        }

        writer.Line(depth, "}");
    }

    /// <summary>
    /// Emitted once per schema rather than once per arity, because every generated
    /// <c>Refine</c> needs it and the arities share this class.
    /// </summary>
    private static void WriteCombine(Writer writer, int depth)
    {
        writer.Line(
            depth,
            "internal static " + Field + "[] Combine(" + Field + "[] first, " + Field + "[] second)");

        writer.Line(depth, "{");
        writer.Line(depth + 1, "if (first == null || first.Length == 0) return second;");
        writer.Line(depth + 1, "if (second == null || second.Length == 0) return first;");
        writer.Blank();
        writer.Line(
            depth + 1,
            "var combined = new " + Field + "[first.Length + second.Length];");

        writer.Line(depth + 1, "first.CopyTo(combined, 0);");
        writer.Line(depth + 1, "second.CopyTo(combined, first.Length);");
        writer.Blank();
        writer.Line(depth + 1, "return combined;");
        writer.Line(depth, "}");
    }

    private static void WriteFieldsOverload(
        Writer writer,
        int depth,
        int arity,
        bool constrained)
    {
        writer.Line(
            depth,
            "/// <summary>Binds " + Count(arity) + " to the value each one builds.</summary>");

        writer.Line(
            depth,
            "/// <remarks>Finish with <c>Into</c> to construct the result, or <c>Checked</c> to gate without constructing one. Add rules that only gate with <c>Refine</c>.</remarks>");

        writer.Line(
            depth,
            "public static " + LadderType + Parameters(arity) + " " + FieldsMember + Parameters(arity) + "(");

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(
                depth + 1,
                Field + "<T" + index + "> field" + index + (index < arity ? "," : ")"));
        }

        WriteConstraints(writer, depth + 1, arity, constrained);

        writer.Line(
            depth + 1,
            "=> new " + LadderType + Parameters(arity) + "(" + Arguments(arity, "field") + ", null);");
    }

    private static void WriteFieldSet(
        Writer writer,
        int depth,
        int arity,
        bool constrained)
    {
        string self = LadderType + Parameters(arity);

        writer.Line(
            depth,
            "/// <summary>" + Count(arity) + " gathered into one parse.</summary>");

        writer.Line(
            depth,
            "/// <remarks>Every field runs whatever the ones before it did, so one call reports every problem with the input rather than the first.</remarks>");

        writer.Line(depth, "private readonly struct " + self);
        WriteConstraints(writer, depth + 1, arity, constrained);
        writer.Line(depth, "{");

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(
                depth + 1,
                "private readonly " + Field + "<T" + index + "> _field" + index + ";");
        }

        writer.Line(depth + 1, "private readonly " + Field + "[] _refinements;");
        writer.Blank();

        WriteFieldSetConstructor(writer, depth + 1, arity);
        writer.Blank();
        WriteRefine(writer, depth + 1, arity, self);
        writer.Blank();
        WriteInto(writer, depth + 1, arity, constrained);
        writer.Blank();
        WriteChecked(writer, depth + 1, arity);

        writer.Line(depth, "}");
    }

    private static void WriteFieldSetConstructor(
        Writer writer,
        int depth,
        int arity)
    {
        writer.Line(depth, "internal " + LadderType + "(");

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(
                depth + 1,
                Field + "<T" + index + "> field" + index + ",");
        }

        writer.Line(depth + 1, Field + "[] refinements)");
        writer.Line(depth, "{");

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(depth + 1, "_field" + index + " = field" + index + ";");
        }

        writer.Line(depth + 1, "_refinements = refinements;");
        writer.Line(depth, "}");
    }

    private static void WriteRefine(
        Writer writer,
        int depth,
        int arity,
        string self)
    {
        writer.Line(
            depth,
            "/// <summary>Adds rules that gate the parse without contributing to it.</summary>");

        writer.Line(
            depth,
            "/// <remarks>Takes the non-generic field, which drops the value side, so a cross-field rule needs no discard at the call site. Calling it more than once adds to the rules already there rather than replacing them.</remarks>");

        writer.Line(
            depth,
            "public " + self + " Refine(params " + Field + "[] refinements) =>");

        writer.Line(
            depth + 1,
            "new " + self + "(" + Arguments(arity, "_field") + ", Schema.Combine(_refinements, refinements));");
    }

    private static void WriteInto(
        Writer writer,
        int depth,
        int arity,
        bool constrained)
    {
        writer.Line(
            depth,
            "/// <summary>Builds the parsed value from the fields, or reports why it could not be.</summary>");

        writer.Line(
            depth,
            "/// <remarks>The delegate runs only when nothing was reported, so it never sees a value a field failed to produce. It is called directly rather than handed to the accumulator, so a passing parse allocates no closure.</remarks>");

        writer.Line(
            depth,
            "public " + Result + "<TOut, " + Violation + "> Into<TOut>(");

        writer.Line(
            depth + 1,
            "global::System.Func<" + Arguments(arity, "T") + ", TOut> build)");

        if (constrained) writer.Line(depth + 1, "where TOut : notnull");

        writer.Line(depth, "{");
        writer.Line(depth + 1, "var accumulator = " + Accumulator + ".Start();");
        writer.Blank();

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(
                depth + 1,
                "T" + index + " value" + index + " = accumulator.Take(_field" + index + ");");
        }

        writer.Blank();
        writer.Line(depth + 1, "if (_refinements != null)");
        writer.Line(depth + 1, "{");
        writer.Line(
            depth + 2,
            "for (int index = 0; index < _refinements.Length; index++)");

        writer.Line(depth + 2, "{");
        writer.Line(depth + 3, "accumulator.Refine(_refinements[index]);");
        writer.Line(depth + 2, "}");
        writer.Line(depth + 1, "}");
        writer.Blank();
        writer.Line(
            depth + 1,
            "if (accumulator.HasViolations) return accumulator.Failed<TOut>();");

        writer.Blank();
        writer.Line(
            depth + 1,
            "return " + Result + ".Ok<TOut, " + Violation + ">(build(" + Arguments(arity, "value") + "));");

        writer.Line(depth, "}");
    }

    private static void WriteChecked(Writer writer, int depth, int arity)
    {
        writer.Line(
            depth,
            "/// <summary>Gates the parse without building anything from it.</summary>");

        writer.Line(
            depth,
            "/// <remarks>For a schema that only validates. The fields still run and still report, and their values are discarded.</remarks>");

        writer.Line(
            depth,
            "public " + Result + "<" + CheckedValue + ", " + Violation + "> Checked() =>");

        writer.Line(
            depth + 1,
            "Into((" + Arguments(arity, "value") + ") => " + CheckedValue + ".Instance);");
    }

    private static void WriteConstraints(
        Writer writer,
        int depth,
        int arity,
        bool constrained)
    {
        if (!constrained) return;

        for (var index = 1; index <= arity; index++)
        {
            writer.Line(depth, "where T" + index + " : notnull");
        }
    }

    private static string Parameters(int arity) =>
        "<" + Arguments(arity, "T") + ">";

    private static string Arguments(int arity, string prefix)
    {
        var text = new StringBuilder();

        for (var index = 1; index <= arity; index++)
        {
            if (index > 1) text.Append(", ");

            text.Append(prefix);
            text.Append(index);
        }

        return text.ToString();
    }

    private static string Count(int arity) =>
        arity == 1 ? "One field" : arity + " fields";

    private sealed class Writer
    {
        private readonly StringBuilder _builder = new StringBuilder();

        public void Line(int depth, string text)
        {
            _builder.Append(' ', depth * 4);
            _builder.Append(text);
            _builder.Append('\n');
        }

        public void Blank() => _builder.Append('\n');

        public override string ToString() => _builder.ToString();
    }
}
