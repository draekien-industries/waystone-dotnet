namespace Waystone.Monads.Schemas.SourceGenerators;

using System.Linq;
using Shouldly;
using Xunit;

public sealed class SchemaGeneratorTests
{
    private const string Configure = """
                protected override Result<string, SchemaViolation> Configure(string subject) =>
                    Schema.Text.Parse(subject);
        """;

    /// <summary>
    /// A schema subject with the given class declaration. Defaulted, because most
    /// cases here differ only in the modifiers on the class or in its name, and a
    /// change to the shell should be one edit rather than ten.
    /// </summary>
    private static string Declaring(
        string declaration = "public partial class GreetingSchema") =>
        $$"""
              {{declaration}} : SchemaConfig<string, string>
              {
          {{Configure}}
              }
          """;

    [Fact]
    public void AConcreteSchemaGetsItsSharedInstance()
    {
        GeneratorRun run = Verify.Run(Declaring());

        run.Source.ShouldBe(
            """
            // <auto-generated/>

            namespace Sample
            {
                partial class GreetingSchema
                {
                    /// <summary>The shared <c>GreetingSchema</c>.</summary>
                    /// <remarks>A schema holds nothing that belongs to one parse, so a single instance serves every call. Reach for this rather than constructing another, including where a schema is the item of a list or a field of an enclosing schema.</remarks>
                    public static global::Sample.GreetingSchema Instance { get; } = new global::Sample.GreetingSchema();
                }
            }

            """);
    }

    [Fact]
    public void TheEmittedSourceCompilesCleanly()
    {
        GeneratorRun run = Verify.Run(Declaring());

        run.CompilationDiagnostics.ShouldBeEmpty();
        run.GeneratorDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void TheHintNameCarriesTheNamespaceAndTheSchemaName()
    {
        GeneratorRun run = Verify.Run(Declaring());

        run.HintNames.Single()
           .ShouldEndWith("Sample.GreetingSchema.Instance.g.cs");
    }

    /// <summary>
    /// A member cannot be more accessible than the type declaring it, so an internal
    /// schema's <c>Instance</c> follows it down rather than being written
    /// <c>public</c> and meaning something narrower.
    /// </summary>
    [Fact]
    public void AnInternalSchemaGetsAnInternalInstance()
    {
        GeneratorRun run = Verify.Run(Declaring("internal partial class GreetingSchema"));

        run.Source.ShouldContain(
            "internal static global::Sample.GreetingSchema Instance");

        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void ASchemaInTheGlobalNamespaceGetsNoNamespaceBlock()
    {
        GeneratorRun run = Verify.RunRaw(
            $$"""
              using Waystone.Monads.Results;
              using Waystone.Monads.Schemas;

              public partial class GreetingSchema : SchemaConfig<string, string>
              {
              {{Configure}}
              }
              """);

        run.Source.ShouldBe(
            """
            // <auto-generated/>

            partial class GreetingSchema
            {
                /// <summary>The shared <c>GreetingSchema</c>.</summary>
                /// <remarks>A schema holds nothing that belongs to one parse, so a single instance serves every call. Reach for this rather than constructing another, including where a schema is the item of a list or a field of an enclosing schema.</remarks>
                public static global::GreetingSchema Instance { get; } = new global::GreetingSchema();
            }

            """);

        run.HintNames.Single().ShouldEndWith("GreetingSchema.Instance.g.cs");
        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void ANestedSchemaReopensEveryTypeAroundIt()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial record Outer
                  {
                      public partial struct Middle
                      {
                          public partial class GreetingSchema : SchemaConfig<string, string>
                          {
                  {{Configure}}
                          }
                      }
                  }
              """);

        run.Source.ShouldContain("partial record Outer");
        run.Source.ShouldContain("partial struct Middle");
        run.Source.ShouldContain("partial class GreetingSchema");

        run.HintNames.Single()
           .ShouldEndWith("Sample.Outer.Middle.GreetingSchema.Instance.g.cs");

        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    /// <summary>
    /// Every kind of type that can nest another gets reopened with its own keyword.
    /// A wrong keyword is a compile error in the generated file, which is the one
    /// file the consumer cannot fix.
    /// </summary>
    [Fact]
    public void EveryKindOfContainerIsReopenedWithItsOwnKeyword()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial interface IOuter
                  {
                      public partial record struct Middle
                      {
                          public partial class GreetingSchema : SchemaConfig<string, string>
                          {
                  {{Configure}}
                          }
                      }
                  }
              """);

        run.Source.ShouldContain("partial interface IOuter");
        run.Source.ShouldContain("partial record struct Middle");
        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void ASchemaWithSeveralTypeParametersKeepsThemAllInOrder()
    {
        GeneratorRun run = Verify.Run(
            Declaring("public partial class PairSchema<TFirst, TSecond>"));

        run.Source.ShouldContain("partial class PairSchema<TFirst, TSecond>");

        run.HintNames.Single()
           .ShouldEndWith("Sample.PairSchema_2.Instance.g.cs");

        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void AGenericSchemaKeepsItsTypeParametersAndDropsItsConstraints()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial class BoxSchema<T> : SchemaConfig<string, string>
                      where T : notnull
                  {
              {{Configure}}
                  }
              """);

        run.Source.ShouldContain("partial class BoxSchema<T>");
        run.Source.ShouldNotContain("where T");

        run.Source.ShouldContain(
            "public static global::Sample.BoxSchema<T> Instance { get; } = new global::Sample.BoxSchema<T>();");

        run.HintNames.Single()
           .ShouldEndWith("Sample.BoxSchema_1.Instance.g.cs");

        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    /// <summary>
    /// An abstract schema exists to be derived from, so it has no shared instance to
    /// offer and nothing about it is wrong. It is skipped without a diagnostic.
    /// </summary>
    [Fact]
    public void AnAbstractSchemaGetsNothingAndNoComplaint()
    {
        GeneratorRun run = Verify.Run(
            """
                public abstract partial class GreetingSchema : SchemaConfig<string, string>
                {
                }
            """);

        run.Generated.ShouldBeEmpty();
        run.GeneratorDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void AClassThatIsNotASchemaGetsNothing()
    {
        GeneratorRun run = Verify.Run(
            """
                public partial class Greeting : System.Collections.Generic.List<string>
                {
                }
            """);

        run.Generated.ShouldBeEmpty();
        run.GeneratorDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void AClassWithNoBaseListGetsNothing()
    {
        GeneratorRun run = Verify.Run(
            """
                public partial class Greeting
                {
                }
            """);

        run.Generated.ShouldBeEmpty();
        run.GeneratorDiagnostics.ShouldBeEmpty();
    }

    /// <summary>
    /// The base clause may be written on any one part, so the generator has to anchor
    /// on the part that carries it rather than on whichever part the compiler happens
    /// to list first.
    /// </summary>
    [Fact]
    public void ASchemaSplitAcrossFilesIsGeneratedExactlyOnce()
    {
        GeneratorRun run = Verify.RunRaw(
            [
                """
                namespace Sample
                {
                    public partial class GreetingSchema
                    {
                    }
                }
                """,
                $$"""
                  using Waystone.Monads.Results;
                  using Waystone.Monads.Schemas;

                  namespace Sample
                  {
                      public partial class GreetingSchema : SchemaConfig<string, string>
                      {
                  {{Configure}}
                      }
                  }
                  """,
            ]);

        run.HintNames.Length.ShouldBe(1);
        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    /// <summary>
    /// Repeating the base clause on every part is legal, and each repetition reaches
    /// the pipeline, so only one of them may emit or the hint names collide.
    /// </summary>
    [Fact]
    public void ASchemaRepeatingItsBaseClauseIsGeneratedExactlyOnce()
    {
        const string Part = """
                            using Waystone.Monads.Results;
                            using Waystone.Monads.Schemas;

                            namespace Sample
                            {
                                public partial class GreetingSchema : SchemaConfig<string, string>
                                {
                                }
                            }
                            """;

        GeneratorRun run = Verify.RunRaw(
            [
                Part,
                $$"""
                  using Waystone.Monads.Results;
                  using Waystone.Monads.Schemas;

                  namespace Sample
                  {
                      public partial class GreetingSchema : SchemaConfig<string, string>
                      {
                  {{Configure}}
                      }
                  }
                  """,
            ]);

        run.HintNames.Length.ShouldBe(1);
        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void ASchemaThatIsNotPartialIsReported()
    {
        GeneratorRun run = Verify.Run(Declaring("public class GreetingSchema"));

        run.Generated.ShouldBeEmpty();
        run.DiagnosticIds.ShouldBe(["WMSC0001"]);

        run.GeneratorDiagnostics.Single()
           .GetMessage()
           .ShouldBe(
                "'GreetingSchema' cannot receive its generated members because 'GreetingSchema' is not declared partial; add the 'partial' modifier to 'GreetingSchema'");
    }

    /// <summary>
    /// The diagnostic names the container rather than the schema, because that is the
    /// declaration the reader has to change.
    /// </summary>
    [Fact]
    public void AContainerThatIsNotPartialIsReportedInsteadOfTheSchema()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public class Outer
                  {
                      public partial class GreetingSchema : SchemaConfig<string, string>
                      {
                  {{Configure}}
                      }
                  }
              """);

        run.Generated.ShouldBeEmpty();

        run.GeneratorDiagnostics.Single()
           .GetMessage()
           .ShouldBe(
                "'GreetingSchema' cannot receive its generated members because 'Outer' is not declared partial; add the 'partial' modifier to 'Outer'");
    }

    [Fact]
    public void ASchemaWithNoParameterlessConstructorIsReported()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial class GreetingSchema : SchemaConfig<string, string>
                  {
                      public GreetingSchema(int _)
                      {
                      }

              {{Configure}}
                  }
              """);

        run.Generated.ShouldBeEmpty();
        run.DiagnosticIds.ShouldBe(["WMSC0002"]);
    }

    /// <summary>
    /// The generated member sits inside the schema, so a constructor hidden from
    /// everyone else is still one it can call.
    /// </summary>
    [Fact]
    public void APrivateParameterlessConstructorIsStillOneTheInstanceCanCall()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial class GreetingSchema : SchemaConfig<string, string>
                  {
                      private GreetingSchema()
                      {
                      }

              {{Configure}}
                  }
              """);

        run.Source.ShouldContain("Instance { get; } = new global::Sample.GreetingSchema();");
        run.CompilationDiagnostics.ShouldBeEmpty();
    }

    [Fact]
    public void ASchemaDeclaringItsOwnInstanceIsReported()
    {
        GeneratorRun run = Verify.Run(
            $$"""
                  public partial class GreetingSchema : SchemaConfig<string, string>
                  {
                      public static GreetingSchema Instance { get; } = new GreetingSchema();

              {{Configure}}
                  }
              """);

        run.Generated.ShouldBeEmpty();
        run.DiagnosticIds.ShouldBe(["WMSC0003"]);
    }

    /// <summary>
    /// Running the same driver twice over separately parsed but identical sources
    /// makes Roslyn compare the pipeline's cached values, which is the only thing
    /// that exercises their equality.
    /// </summary>
    [Fact]
    public void TheSecondRunOverTheSameSourceProducesTheSameOutput()
    {
        (string first, string second) = Verify.RunTwice(Declaring());

        second.ShouldBe(first);
    }

    [Fact]
    public void TheSecondRunOverDifferentSourceRebuilds()
    {
        (string first, string second) = Verify.RunTwice(
            Declaring(),
            Declaring("public partial class FarewellSchema"));

        second.ShouldNotBe(first);
        second.ShouldContain("FarewellSchema");
    }
}
